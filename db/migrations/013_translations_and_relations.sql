-- Bản dịch nguồn và quan hệ nghĩa chưa đủ chắc để gắn thẳng vào concept.

CREATE TABLE core.translation_assertion (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_lexeme_id bigint NOT NULL REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  source_sense_id bigint REFERENCES core.sense(id) ON DELETE RESTRICT,
  target_language_id smallint NOT NULL REFERENCES public.language(id),
  target_text      text NOT NULL CHECK (btrim(target_text) <> ''),
  romanization     text,
  tags             jsonb NOT NULL DEFAULT '[]'::jsonb
                   CHECK (jsonb_typeof(tags) = 'array'),
  sense_hint       text,
  scope            text NOT NULL CHECK (scope IN ('entry','sense')),
  source_ordinal   smallint NOT NULL CHECK (source_ordinal > 0),
  source_key       text NOT NULL,
  source_id        integer REFERENCES public.source(id),
  batch_id         uuid REFERENCES staging.import_batch(id),
  mapping_run_id   bigint REFERENCES core.mapping_run(id),
  UNIQUE (source_key)
);

CREATE INDEX translation_assertion_source
  ON core.translation_assertion (source_lexeme_id, source_sense_id);
CREATE INDEX translation_assertion_target
  ON core.translation_assertion (target_language_id, target_text);

CREATE TABLE core.translation_target_candidate (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assertion_id    bigint NOT NULL REFERENCES core.translation_assertion(id) ON DELETE RESTRICT,
  target_lexeme_id bigint REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  target_sense_id bigint REFERENCES core.sense(id) ON DELETE RESTRICT,
  score           real CHECK (score >= 0 AND score <= 1),
  match_method    text NOT NULL,
  decision        text NOT NULL DEFAULT 'pending'
                  CHECK (decision IN ('pending','accepted','rejected','uncertain')),
  evidence        jsonb NOT NULL DEFAULT '{}'::jsonb
                  CHECK (jsonb_typeof(evidence) = 'object'),
  mapping_run_id  bigint REFERENCES core.mapping_run(id),
  UNIQUE (assertion_id, target_lexeme_id, target_sense_id, match_method)
);

CREATE INDEX translation_candidate_queue
  ON core.translation_target_candidate (decision, score DESC);

CREATE TABLE core.sense_relation_candidate (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_sense_id  bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  target_sense_id  bigint REFERENCES core.sense(id) ON DELETE RESTRICT,
  target_lexeme_text text,
  target_reading   text,
  relation         text NOT NULL CHECK (relation IN ('equivalent','related','antonym','broader','narrower')),
  source_key       text NOT NULL,
  decision         text NOT NULL DEFAULT 'pending'
                   CHECK (decision IN ('pending','accepted','rejected','uncertain')),
  score            real CHECK (score >= 0 AND score <= 1),
  method           text NOT NULL,
  evidence         jsonb NOT NULL DEFAULT '{}'::jsonb
                   CHECK (jsonb_typeof(evidence) = 'object'),
  mapping_run_id   bigint REFERENCES core.mapping_run(id),
  UNIQUE (source_key)
);

CREATE INDEX sense_relation_candidate_queue
  ON core.sense_relation_candidate (decision, relation, score DESC);

CREATE TABLE core.sense_relation (
  source_sense_id bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  target_sense_id bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  relation        text NOT NULL CHECK (relation IN ('equivalent','related','antonym','broader','narrower')),
  confidence      real CHECK (confidence >= 0 AND confidence <= 1),
  method          text NOT NULL,
  verified        boolean NOT NULL DEFAULT false,
  mapping_run_id  bigint REFERENCES core.mapping_run(id),
  source_id       integer REFERENCES public.source(id),
  batch_id        uuid REFERENCES staging.import_batch(id),
  PRIMARY KEY (source_sense_id, target_sense_id, relation)
);

CREATE INDEX sense_relation_target ON core.sense_relation (target_sense_id, relation);
