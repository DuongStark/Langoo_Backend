-- Nền tảng cho các lần chạy mapping: provenance, candidate và rollback theo run.

CREATE TABLE core.mapping_run (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key         text NOT NULL UNIQUE,
  task            text NOT NULL CHECK (btrim(task) <> ''),
  algorithm       text NOT NULL CHECK (btrim(algorithm) <> ''),
  model           text,
  prompt_version  text,
  source_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb
                  CHECK (jsonb_typeof(source_snapshot) = 'object'),
  parameters      jsonb NOT NULL DEFAULT '{}'::jsonb
                  CHECK (jsonb_typeof(parameters) = 'object'),
  status          text NOT NULL DEFAULT 'running'
                  CHECK (status IN ('running','dry_run','completed','failed','rolled_back')),
  started_at      timestamptz NOT NULL DEFAULT now(),
  finished_at     timestamptz,
  rows_seen       bigint,
  rows_accepted   bigint,
  rows_rejected   bigint,
  rows_unresolved bigint,
  error           text
);

CREATE INDEX mapping_run_task_status ON core.mapping_run (task, status, started_at DESC);

-- Crosswalk bền vững cho entry nguồn. staging_row_id chỉ là con trỏ của
-- snapshot hiện tại; source_external_id/logical_key mới được dùng khi refresh.
CREATE TABLE core.source_entry_identity (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id          integer NOT NULL REFERENCES public.source(id),
  source_snapshot    text NOT NULL,
  source_external_id text NOT NULL,
  logical_key        text NOT NULL,
  language_id        smallint REFERENCES public.language(id),
  word               text,
  pos                text,
  source_ordinal     integer,
  content_hash       text,
  staging_row_id     bigint,
  lexeme_id          bigint REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  status             text NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active','changed','removed','ambiguous','unresolved')),
  attributes         jsonb NOT NULL DEFAULT '{}'::jsonb
                     CHECK (jsonb_typeof(attributes) = 'object'),
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, source_snapshot, source_external_id)
);

CREATE INDEX source_entry_identity_logical
  ON core.source_entry_identity (source_id, logical_key, status);
CREATE INDEX source_entry_identity_lexeme
  ON core.source_entry_identity (lexeme_id)
  WHERE lexeme_id IS NOT NULL;

ALTER TABLE core.sense_concept
  ADD COLUMN mapping_run_id bigint REFERENCES core.mapping_run(id),
  ADD COLUMN decided_at timestamptz;

CREATE TABLE core.sense_concept_candidate (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id          bigint NOT NULL REFERENCES core.mapping_run(id) ON DELETE RESTRICT,
  sense_id        bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  concept_id      bigint NOT NULL REFERENCES core.concept(id) ON DELETE RESTRICT,
  relation        text NOT NULL DEFAULT 'exact'
                  CHECK (relation IN ('exact','broader','narrower','related')),
  score           real CHECK (score >= 0 AND score <= 1),
  calibrated_score real CHECK (calibrated_score >= 0 AND calibrated_score <= 1),
  decision        text NOT NULL DEFAULT 'pending'
                  CHECK (decision IN ('pending','accepted','rejected','stale','uncertain')),
  method          text NOT NULL CHECK (btrim(method) <> ''),
  evidence        jsonb NOT NULL DEFAULT '{}'::jsonb
                  CHECK (jsonb_typeof(evidence) = 'object'),
  llm_result      jsonb NOT NULL DEFAULT '{}'::jsonb
                  CHECK (jsonb_typeof(llm_result) = 'object'),
  artifact_hash   text,
  decided_at      timestamptz,
  UNIQUE (run_id, sense_id, concept_id, relation)
);

CREATE INDEX sense_concept_candidate_queue
  ON core.sense_concept_candidate (decision, run_id, score DESC);
CREATE INDEX sense_concept_candidate_sense
  ON core.sense_concept_candidate (sense_id, decision, calibrated_score DESC);
