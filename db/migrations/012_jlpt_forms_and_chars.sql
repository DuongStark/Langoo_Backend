-- Giữ mọi dòng JLPT, form Wiktextract và mọi ký tự trong form JMdict.

CREATE TABLE core.jlpt_link (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_level      smallint NOT NULL,
  source_row_number integer NOT NULL,
  variant_index     smallint NOT NULL DEFAULT 1 CHECK (variant_index > 0),
  expression       text NOT NULL,
  reading          text,
  lexeme_id        bigint REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  status            text NOT NULL DEFAULT 'unresolved'
                    CHECK (status IN ('accepted','ambiguous','unmatched','pattern','unresolved','rejected')),
  match_method      text,
  score             real CHECK (score >= 0 AND score <= 1),
  evidence          jsonb NOT NULL DEFAULT '{}'::jsonb
                    CHECK (jsonb_typeof(evidence) = 'object'),
  mapping_run_id    bigint REFERENCES core.mapping_run(id),
  source_id         integer NOT NULL REFERENCES public.source(id),
  batch_id          uuid NOT NULL REFERENCES staging.import_batch(id),
  FOREIGN KEY (source_level, source_row_number)
    REFERENCES staging.jlpt_entry(level, row_number),
  UNIQUE (source_level, source_row_number, variant_index, lexeme_id)
);

CREATE INDEX jlpt_link_status ON core.jlpt_link (status, source_level, expression);
CREATE INDEX jlpt_link_lexeme ON core.jlpt_link (lexeme_id, status);

CREATE TABLE core.source_form (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lexeme_id      bigint NOT NULL REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  form_text      text NOT NULL CHECK (btrim(form_text) <> ''),
  form_kind      text NOT NULL DEFAULT 'source'
                 CHECK (btrim(form_kind) <> ''),
  tags           jsonb NOT NULL DEFAULT '[]'::jsonb
                 CHECK (jsonb_typeof(tags) = 'array'),
  attributes     jsonb NOT NULL DEFAULT '{}'::jsonb
                 CHECK (jsonb_typeof(attributes) = 'object'),
  source_ordinal smallint NOT NULL CHECK (source_ordinal > 0),
  source_id      integer REFERENCES public.source(id),
  batch_id       uuid REFERENCES staging.import_batch(id),
  UNIQUE (lexeme_id, form_text, form_kind, source_ordinal)
);

CREATE INDEX source_form_lookup ON core.source_form (form_text, form_kind);
CREATE INDEX source_form_lexeme ON core.source_form (lexeme_id, form_kind);

CREATE TABLE core.lexeme_form_char (
  form_id         bigint NOT NULL REFERENCES core.lexeme_form(id) ON DELETE CASCADE,
  char_position   integer NOT NULL CHECK (char_position > 0),
  literal         text NOT NULL CHECK (char_length(literal) = 1),
  codepoint_ucs   integer NOT NULL CHECK (codepoint_ucs BETWEEN 0 AND 1114111),
  character_kind  text NOT NULL CHECK (character_kind IN (
                    'kanji','kana','latin','digit','punctuation','symbol','other')),
  kanji_literal   text REFERENCES core.kanji(literal) ON DELETE RESTRICT,
  PRIMARY KEY (form_id, char_position)
);

CREATE INDEX lexeme_form_char_literal ON core.lexeme_form_char (literal, character_kind);
CREATE INDEX lexeme_form_char_kanji ON core.lexeme_form_char (kanji_literal)
  WHERE kanji_literal IS NOT NULL;
