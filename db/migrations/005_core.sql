-- 005_core.sql — từ điển chuẩn hóa; PostgreSQL 16+.
-- 001–004 đã được dùng cho metadata và staging. Migration chạy trong một
-- transaction bởi scripts/apply_migrations.py; không dùng IF NOT EXISTS cho
-- bảng core để phát hiện schema trôi khỏi lịch sử migration.

CREATE SCHEMA core;

-- Đồng bộ 3 tên POS cũ với taxonomy đã chốt. Mã JMdict gốc vẫn ở tag.code.
UPDATE public.tag
SET pos_norm = CASE pos_norm
  WHEN 'numeral'      THEN 'noun'
  WHEN 'copula'       THEN 'auxiliary'
  WHEN 'unclassified' THEN 'unknown'
  WHEN 'other'        THEN 'unknown'
  ELSE COALESCE(pos_norm, 'unknown')
END
WHERE kind = 'pos';

ALTER TABLE public.tag ADD CONSTRAINT tag_pos_norm_valid CHECK (
  (kind = 'pos' AND pos_norm IS NOT NULL AND pos_norm IN (
    'noun', 'verb', 'adjective', 'adverb', 'pronoun', 'determiner',
    'particle', 'auxiliary', 'conjunction', 'interjection', 'expression',
    'counter', 'prefix', 'suffix', 'unknown'
  )) OR (kind <> 'pos' AND pos_norm IS NULL)
);

-- Một entry JMdict tương ứng một lexeme. attributes.kanji/kana là mảng text
-- để tra cứu; attributes.kanji_forms/kana_forms giữ cả common, tags và
-- appliesToKanji của từng dạng. Staging vẫn giữ nguyên payload nguồn.
CREATE TABLE core.lexeme (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id    smallint NOT NULL REFERENCES public.language(id),
  lemma          text NOT NULL CHECK (btrim(lemma) <> ''),
  pos            text NOT NULL DEFAULT 'unknown' CHECK (pos IN (
    'noun', 'verb', 'adjective', 'adverb', 'pronoun', 'determiner',
    'particle', 'auxiliary', 'conjunction', 'interjection', 'expression',
    'counter', 'prefix', 'suffix', 'unknown'
  )),
  reading        text,
  romanization   text,
  homograph_no   smallint NOT NULL DEFAULT 1 CHECK (homograph_no > 0),
  frequency_rank integer CHECK (frequency_rank > 0),
  attributes     jsonb NOT NULL DEFAULT '{}'::jsonb
                 CHECK (jsonb_typeof(attributes) = 'object'),
  external_id    text UNIQUE CHECK (external_id IS NULL OR btrim(external_id) <> ''),
  source_id      integer REFERENCES public.source(id),
  batch_id       uuid REFERENCES staging.import_batch(id),
  content_hash   text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT lexeme_natural_key UNIQUE (language_id, lemma, pos, homograph_no),
  CONSTRAINT lexeme_external_source CHECK (external_id IS NULL OR source_id IS NOT NULL)
);

-- Exact/prefix lookup; biến thể trong attributes là JSONB array of strings.
CREATE INDEX lexeme_lemma_lookup ON core.lexeme (language_id, lemma);
CREATE INDEX lexeme_reading_lookup ON core.lexeme (language_id, reading)
  WHERE reading IS NOT NULL;
CREATE INDEX lexeme_lemma_prefix ON core.lexeme (lemma text_pattern_ops);
CREATE INDEX lexeme_reading_prefix ON core.lexeme (reading text_pattern_ops)
  WHERE reading IS NOT NULL;
CREATE INDEX lexeme_kanji_forms ON core.lexeme
  USING gin ((attributes -> 'kanji') jsonb_path_ops);
CREATE INDEX lexeme_kana_forms ON core.lexeme
  USING gin ((attributes -> 'kana') jsonb_path_ops);
CREATE INDEX lexeme_frequency ON core.lexeme (language_id, frequency_rank)
  WHERE frequency_rank IS NOT NULL;

-- Một sense là một nghĩa của lexeme. definition dành cho định nghĩa cùng
-- ngôn ngữ của lexeme; gloss nguồn ở ngôn ngữ khác nằm trong sense_gloss.
CREATE TABLE core.sense (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lexeme_id   bigint NOT NULL REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  sense_no    smallint NOT NULL CHECK (sense_no > 0),
  definition  text,
  register    text CHECK (register IN ('formal', 'colloquial', 'archaic', 'slang')),
  domain      text,
  is_primary  boolean NOT NULL DEFAULT false,
  external_id text UNIQUE CHECK (external_id IS NULL OR btrim(external_id) <> ''),
  attributes  jsonb NOT NULL DEFAULT '{}'::jsonb
              CHECK (jsonb_typeof(attributes) = 'object'),
  source_id   integer REFERENCES public.source(id),
  batch_id    uuid REFERENCES staging.import_batch(id),
  CONSTRAINT sense_order_per_lexeme UNIQUE (lexeme_id, sense_no),
  CONSTRAINT sense_external_source CHECK (external_id IS NULL OR source_id IS NOT NULL)
);
CREATE UNIQUE INDEX sense_one_primary ON core.sense (lexeme_id) WHERE is_primary;

-- Tag gốc theo từng nghĩa: POS, misc, field, dialect. Các tag thuộc một
-- dạng kanji/kana cụ thể được giữ cùng dạng đó ở lexeme.attributes.
CREATE TABLE core.sense_tag (
  sense_id bigint NOT NULL REFERENCES core.sense(id) ON DELETE CASCADE,
  tag_code text NOT NULL REFERENCES public.tag(code),
  PRIMARY KEY (sense_id, tag_code)
);
CREATE INDEX sense_tag_code ON core.sense_tag (tag_code, sense_id);

CREATE TABLE core.sense_gloss (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sense_id    bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  language_id smallint NOT NULL REFERENCES public.language(id),
  text        text NOT NULL CHECK (btrim(text) <> ''),
  detail      text,
  is_machine  boolean NOT NULL DEFAULT false,
  reviewed_by bigint,
  reviewed_at timestamptz,
  quality     smallint CHECK (quality BETWEEN 0 AND 100),
  rank        smallint NOT NULL DEFAULT 1 CHECK (rank > 0),
  source_id   integer REFERENCES public.source(id),
  batch_id    uuid REFERENCES staging.import_batch(id),
  CONSTRAINT sense_gloss_slot UNIQUE (sense_id, language_id, rank),
  CONSTRAINT sense_gloss_review_pair CHECK (
    (reviewed_by IS NULL) = (reviewed_at IS NULL)
  )
);
CREATE INDEX sense_gloss_language ON core.sense_gloss (language_id, sense_id);

-- ILI là khóa liên ngữ; concept tự tạo có thể chưa có ILI.
CREATE TABLE core.concept (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ili       text UNIQUE CHECK (ili IS NULL OR btrim(ili) <> ''),
  pos       text CHECK (pos IN (
    'noun', 'verb', 'adjective', 'adverb', 'pronoun', 'determiner',
    'particle', 'auxiliary', 'conjunction', 'interjection', 'expression',
    'counter', 'prefix', 'suffix', 'unknown'
  )),
  gloss_en  text,
  gloss_vi  text,
  cefr      text,
  status    text NOT NULL DEFAULT 'draft'
            CHECK (status IN ('draft', 'review', 'curated', 'rejected')),
  source_id integer REFERENCES public.source(id),
  batch_id  uuid REFERENCES staging.import_batch(id)
);
CREATE INDEX concept_curated ON core.concept (id) WHERE status = 'curated';

-- Mọi ứng viên gloss cấp concept, với nguồn và trạng thái duyệt riêng.
CREATE TABLE core.concept_gloss (
  concept_id  bigint NOT NULL REFERENCES core.concept(id) ON DELETE RESTRICT,
  language_id smallint NOT NULL REFERENCES public.language(id),
  rank        smallint NOT NULL DEFAULT 1 CHECK (rank > 0),
  text        text NOT NULL CHECK (btrim(text) <> ''),
  is_machine  boolean NOT NULL DEFAULT false,
  quality     smallint CHECK (quality BETWEEN 0 AND 100),
  reviewed_by bigint,
  reviewed_at timestamptz,
  source_id   integer REFERENCES public.source(id),
  batch_id    uuid REFERENCES staging.import_batch(id),
  PRIMARY KEY (concept_id, language_id, rank),
  CONSTRAINT concept_gloss_review_pair CHECK (
    (reviewed_by IS NULL) = (reviewed_at IS NULL)
  )
);

-- Lưu ảnh trước/sau mỗi thay đổi nội dung gloss, kể cả khi xóa. Không FK tới
-- gloss gốc để lịch sử vẫn còn sau khi một bản ghi bị xóa nhầm.
CREATE TABLE core.sense_gloss_history (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gloss_id   bigint NOT NULL,
  event      text NOT NULL CHECK (event IN ('update', 'delete')),
  old_data   jsonb NOT NULL,
  new_data   jsonb,
  changed_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sense_gloss_history_shape CHECK (
    (event = 'update' AND new_data IS NOT NULL) OR
    (event = 'delete' AND new_data IS NULL)
  )
);
CREATE INDEX sense_gloss_history_by_gloss
  ON core.sense_gloss_history (gloss_id, changed_at DESC);

CREATE TABLE core.concept_gloss_history (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concept_id  bigint NOT NULL,
  language_id smallint NOT NULL,
  rank        smallint NOT NULL,
  event       text NOT NULL CHECK (event IN ('update', 'delete')),
  old_data    jsonb NOT NULL,
  new_data    jsonb,
  changed_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT concept_gloss_history_shape CHECK (
    (event = 'update' AND new_data IS NOT NULL) OR
    (event = 'delete' AND new_data IS NULL)
  )
);
CREATE INDEX concept_gloss_history_by_gloss
  ON core.concept_gloss_history (concept_id, language_id, rank, changed_at DESC);

CREATE FUNCTION core.audit_sense_gloss() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    INSERT INTO core.sense_gloss_history (gloss_id, event, old_data)
    VALUES (OLD.id, 'delete', to_jsonb(OLD));
    RETURN OLD;
  END IF;

  IF (to_jsonb(OLD) - 'batch_id') IS DISTINCT FROM
     (to_jsonb(NEW) - 'batch_id') THEN
    INSERT INTO core.sense_gloss_history (gloss_id, event, old_data, new_data)
    VALUES (OLD.id, 'update', to_jsonb(OLD), to_jsonb(NEW));
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER sense_gloss_audit
AFTER UPDATE OR DELETE ON core.sense_gloss
FOR EACH ROW EXECUTE FUNCTION core.audit_sense_gloss();

CREATE FUNCTION core.audit_concept_gloss() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    INSERT INTO core.concept_gloss_history
      (concept_id, language_id, rank, event, old_data)
    VALUES (OLD.concept_id, OLD.language_id, OLD.rank, 'delete', to_jsonb(OLD));
    RETURN OLD;
  END IF;

  IF (to_jsonb(OLD) - 'batch_id') IS DISTINCT FROM
     (to_jsonb(NEW) - 'batch_id') THEN
    INSERT INTO core.concept_gloss_history
      (concept_id, language_id, rank, event, old_data, new_data)
    VALUES (OLD.concept_id, OLD.language_id, OLD.rank,
            'update', to_jsonb(OLD), to_jsonb(NEW));
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER concept_gloss_audit
AFTER UPDATE OR DELETE ON core.concept_gloss
FOR EACH ROW EXECUTE FUNCTION core.audit_concept_gloss();

-- Gắn sense với concept ở cấp nghĩa; không gộp lexeme theo cách viết.
CREATE TABLE core.sense_concept (
  sense_id   bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  concept_id bigint NOT NULL REFERENCES core.concept(id) ON DELETE RESTRICT,
  relation   text NOT NULL DEFAULT 'exact'
             CHECK (relation IN ('exact', 'broader', 'narrower', 'related')),
  confidence real NOT NULL DEFAULT 1.0
             CHECK (confidence >= 0.0 AND confidence <= 1.0),
  method     text NOT NULL CHECK (btrim(method) <> ''),
  verified   boolean NOT NULL DEFAULT false,
  source_id  integer REFERENCES public.source(id),
  batch_id   uuid REFERENCES staging.import_batch(id),
  PRIMARY KEY (sense_id, concept_id)
);
CREATE INDEX sense_concept_by_concept
  ON core.sense_concept (concept_id, confidence DESC);

-- KANJIDIC2 và KRADFILE có độ phủ khác nhau. Tạo kanji từ hợp của hai nguồn;
-- các thuộc tính có thể NULL khi nguồn tương ứng không có chữ đó.
CREATE TABLE core.kanji (
  literal           text PRIMARY KEY CHECK (char_length(literal) = 1),
  codepoint_ucs     integer CHECK (codepoint_ucs BETWEEN 0 AND 1114111),
  grade             smallint CHECK (grade > 0),
  stroke_count      smallint CHECK (stroke_count > 0),
  frequency_rank    integer CHECK (frequency_rank > 0),
  jlpt_old          smallint CHECK (jlpt_old BETWEEN 1 AND 4),
  radical_classical smallint CHECK (radical_classical BETWEEN 1 AND 214),
  readings          jsonb NOT NULL DEFAULT '{}'::jsonb
                    CHECK (jsonb_typeof(readings) = 'object'),
  meanings          jsonb NOT NULL DEFAULT '{}'::jsonb
                    CHECK (jsonb_typeof(meanings) = 'object'),
  nanori            jsonb NOT NULL DEFAULT '[]'::jsonb
                    CHECK (jsonb_typeof(nanori) = 'array'),
  query_codes       jsonb NOT NULL DEFAULT '{}'::jsonb
                    CHECK (jsonb_typeof(query_codes) = 'object'),
  dict_refs         jsonb NOT NULL DEFAULT '[]'::jsonb
                    CHECK (jsonb_typeof(dict_refs) = 'array'),
  source_id         integer REFERENCES public.source(id),
  batch_id          uuid REFERENCES staging.import_batch(id)
);
CREATE INDEX kanji_frequency ON core.kanji (frequency_rank)
  WHERE frequency_rank IS NOT NULL;

CREATE TABLE core.kanji_radical (
  kanji_literal text NOT NULL REFERENCES core.kanji(literal) ON DELETE CASCADE,
  part          text NOT NULL CHECK (btrim(part) <> ''),
  position      smallint CHECK (position > 0),
  source_id     integer REFERENCES public.source(id),
  batch_id      uuid REFERENCES staging.import_batch(id),
  PRIMARY KEY (kanji_literal, part)
);
COMMENT ON COLUMN core.kanji_radical.position IS
  'Thứ tự trong KRADFILE; không phải thứ tự viết nét.';
CREATE INDEX kanji_radical_part ON core.kanji_radical (part, kanji_literal);

-- Một câu có thể minh họa nhiều nghĩa; external_id vì thế không unique toàn bảng.
-- sense_id NULL cho câu chưa gắn nghĩa, để importer có thể nạp trước khi tokenize.
CREATE TABLE core.example (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sense_id    bigint REFERENCES core.sense(id) ON DELETE RESTRICT,
  language_id smallint NOT NULL REFERENCES public.language(id),
  text        text NOT NULL CHECK (btrim(text) <> ''),
  translation jsonb NOT NULL DEFAULT '{}'::jsonb
              CHECK (jsonb_typeof(translation) = 'object'),
  external_id text CHECK (external_id IS NULL OR btrim(external_id) <> ''),
  difficulty smallint CHECK (difficulty >= 0),
  source_id   integer REFERENCES public.source(id),
  batch_id    uuid REFERENCES staging.import_batch(id),
  CONSTRAINT example_external_source CHECK (external_id IS NULL OR source_id IS NOT NULL)
);
CREATE INDEX example_by_sense ON core.example (sense_id, language_id)
  WHERE sense_id IS NOT NULL;
CREATE INDEX example_by_external_id ON core.example (external_id)
  WHERE external_id IS NOT NULL;
CREATE UNIQUE INDEX example_source_per_sense
  ON core.example (sense_id, external_id)
  WHERE sense_id IS NOT NULL AND external_id IS NOT NULL;
CREATE UNIQUE INDEX example_unlinked_source
  ON core.example (external_id)
  WHERE sense_id IS NULL AND external_id IS NOT NULL;

CREATE TABLE core.pronunciation (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lexeme_id bigint NOT NULL REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  ipa       text,
  audio_key text,
  dialect   text,
  source_id integer REFERENCES public.source(id),
  batch_id  uuid REFERENCES staging.import_batch(id),
  CONSTRAINT pronunciation_has_content CHECK (
    (ipa IS NOT NULL AND btrim(ipa) <> '') OR
    (audio_key IS NOT NULL AND btrim(audio_key) <> '')
  )
);
CREATE INDEX pronunciation_by_lexeme ON core.pronunciation (lexeme_id);
