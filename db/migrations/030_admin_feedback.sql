-- 030_admin_feedback.sql — M13: vai admin, hộp thư feedback (text + ảnh) và audit log.
--
-- Nguyên tắc: admin chỉ đọc dữ liệu tổng hợp; dữ liệu chi tiết duy nhất là thứ
-- người dùng CHỦ ĐỘNG gửi (gloss_report, feedback). Mọi mutation admin ghi
-- app.admin_audit_log trong cùng transaction (service giữ).

ALTER TABLE app.users
  ADD COLUMN role text NOT NULL DEFAULT 'user'
  CHECK (role IN ('user', 'admin'));
CREATE INDEX users_admin ON app.users (id) WHERE role = 'admin';

CREATE TABLE app.feedback (
  id          uuid PRIMARY KEY,
  user_id     bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  category    text NOT NULL CHECK (category IN ('bug', 'feature', 'content', 'other')),
  content     text NOT NULL CHECK (btrim(content) <> ''),
  status      text NOT NULL DEFAULT 'new'
              CHECK (status IN ('new', 'in_progress', 'resolved')),
  admin_note  text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX feedback_queue ON app.feedback (status, created_at);
CREATE TRIGGER feedback_touch BEFORE UPDATE ON app.feedback
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

-- Ảnh lưu qua StorageService (local dev / s3 production); DB chỉ giữ metadata.
CREATE TABLE app.feedback_attachment (
  id          uuid PRIMARY KEY,
  feedback_id uuid NOT NULL REFERENCES app.feedback(id) ON DELETE CASCADE,
  storage_key text NOT NULL CHECK (btrim(storage_key) <> ''),
  mime        text NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp')),
  size_bytes  integer NOT NULL CHECK (size_bytes > 0),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX feedback_attachment_by_feedback
  ON app.feedback_attachment (feedback_id);

-- Nhật ký thao tác admin (khoá/mở user, xử lý feedback/gloss_report…).
CREATE TABLE app.admin_audit_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_user_id bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  action        text NOT NULL CHECK (btrim(action) <> ''),
  target_kind   text,
  target_id     text,
  payload       jsonb NOT NULL DEFAULT '{}'::jsonb
                CHECK (jsonb_typeof(payload) = 'object'),
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX admin_audit_recent ON app.admin_audit_log (created_at DESC);
