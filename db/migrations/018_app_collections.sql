-- 016_app_collections.sql — sổ tay (collection) + bộ thẻ của người học.
--
-- Nguyên tắc thiết kế đã chốt: KHÔNG có bảng cards riêng. Mỗi collection_item
-- là một entry với nghĩa tiếng Việt làm trục chính, các "mặt" ngôn ngữ nằm ở
-- app.collection_item_face (en/ja, mở rộng zh/ko là thêm dòng, không đổi
-- schema). Chế độ flashcard chỉ là tầng đọc của đúng dữ liệu này.
--
-- cloned_from_deck_id / added_from_deck_id giữ dạng bigint chưa FK vì
-- core.deck được tạo ở 024_core_reference.sql; FK được thêm ở đó.

CREATE TABLE app.collection (
  id                         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id                 uuid NOT NULL REFERENCES app.study_profile(id) ON DELETE CASCADE,
  owner_id                   bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  name                       text NOT NULL CHECK (btrim(name) <> ''),
  description                text,
  kind                       text NOT NULL DEFAULT 'personal'
                             CHECK (kind IN ('personal', 'cloned', 'shared')),
  cloned_from_deck_id        bigint,
  cloned_from_collection_id  uuid REFERENCES app.collection(id) ON DELETE SET NULL,
  is_public                  boolean NOT NULL DEFAULT false,
  item_count                 integer NOT NULL DEFAULT 0 CHECK (item_count >= 0),
  created_at                 timestamptz NOT NULL DEFAULT now(),
  updated_at                 timestamptz NOT NULL DEFAULT now(),
  archived_at                timestamptz
);
CREATE INDEX collection_by_profile
  ON app.collection (profile_id, archived_at, updated_at DESC);
CREATE INDEX collection_public ON app.collection (is_public) WHERE is_public;
CREATE TRIGGER collection_touch BEFORE UPDATE ON app.collection
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

-- Một entry = một nghĩa tiếng Việt (user có thể sửa) + 0..n mặt ngôn ngữ.
-- concept_id NULL khi từ chưa nối được concept — entry vẫn học đơn ngữ bình
-- thường. meaning_source ghi vết nghĩa đến từ đâu để UI hiện badge phù hợp.
CREATE TABLE app.collection_item (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  collection_id      uuid NOT NULL REFERENCES app.collection(id) ON DELETE CASCADE,
  concept_id         bigint REFERENCES core.concept(id) ON DELETE RESTRICT,
  anchor_sense_id    bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  meaning_vi         text NOT NULL CHECK (btrim(meaning_vi) <> ''),
  meaning_source     text NOT NULL DEFAULT 'user'
                     CHECK (meaning_source IN ('user', 'source', 'machine', 'llm')),
  note               text,
  status             text NOT NULL DEFAULT 'learning'
                     CHECK (status IN ('learning', 'paused', 'known')),
  position           integer NOT NULL DEFAULT 1 CHECK (position > 0),
  added_from_deck_id bigint,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (collection_id, anchor_sense_id)
);
CREATE INDEX collection_item_by_collection
  ON app.collection_item (collection_id, position);
CREATE INDEX collection_item_by_concept
  ON app.collection_item (concept_id) WHERE concept_id IS NOT NULL;
CREATE TRIGGER collection_item_touch BEFORE UPDATE ON app.collection_item
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

-- Mặt ngôn ngữ của entry: mỗi entry tối đa 1 mặt / ngôn ngữ. sense_id phải
-- thuộc đúng language_id — ràng buộc xuyên bảng do service kiểm tra khi ghi.
CREATE TABLE app.collection_item_face (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id     uuid NOT NULL REFERENCES app.collection_item(id) ON DELETE CASCADE,
  sense_id    bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  language_id smallint NOT NULL REFERENCES public.language(id),
  role        text NOT NULL DEFAULT 'primary'
              CHECK (role IN ('primary', 'secondary')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (item_id, language_id),
  UNIQUE (item_id, sense_id)
);
CREATE INDEX item_face_by_sense ON app.collection_item_face (sense_id);

-- Tag người dùng (#khó, #cần-ôn…) — khác public.tag (mã JMdict) về namespace
-- và vòng đời; không gộp chung.
CREATE TABLE app.tag (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  name       text NOT NULL CHECK (btrim(name) <> ''),
  color      text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Unique theo biểu thức phải là index, không nhét được vào table constraint.
CREATE UNIQUE INDEX tag_user_name_unique ON app.tag (user_id, lower(name));

CREATE TABLE app.collection_item_tag (
  item_id uuid NOT NULL REFERENCES app.collection_item(id) ON DELETE CASCADE,
  tag_id  bigint NOT NULL REFERENCES app.tag(id) ON DELETE CASCADE,
  PRIMARY KEY (item_id, tag_id)
);
CREATE INDEX item_tag_by_tag ON app.collection_item_tag (tag_id, item_id);

-- Chia sẻ collection (Phase 2): link có token, thu hồi được, giới hạn quyền.
CREATE TABLE app.collection_share (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  collection_id uuid NOT NULL REFERENCES app.collection(id) ON DELETE CASCADE,
  token         text NOT NULL UNIQUE CHECK (btrim(token) <> ''),
  permission    text NOT NULL DEFAULT 'view'
                CHECK (permission IN ('view', 'clone')),
  created_by    bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  expires_at    timestamptz,
  revoked_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX collection_share_by_collection
  ON app.collection_share (collection_id) WHERE revoked_at IS NULL;
