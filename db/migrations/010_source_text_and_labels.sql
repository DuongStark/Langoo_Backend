ALTER TABLE core.sense
  ADD COLUMN definition_language_id smallint REFERENCES public.language(id);

-- Wiktextract có thể dùng gloss tiếng Anh cho entry tiếng Nhật/Việt; cột này
-- làm rõ ngôn ngữ thực của nội dung, không suy ra từ language_id của lexeme.
COMMENT ON COLUMN core.sense.definition_language_id IS
  'Ngôn ngữ của definition cache; có thể khác ngôn ngữ của lexeme.';

CREATE TABLE core.concept_label (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concept_id   bigint NOT NULL REFERENCES core.concept(id) ON DELETE RESTRICT,
  language_id  smallint NOT NULL REFERENCES public.language(id),
  rank         smallint NOT NULL DEFAULT 1 CHECK (rank > 0),
  text         text NOT NULL CHECK (btrim(text) <> ''),
  label_kind   text NOT NULL DEFAULT 'lemma'
               CHECK (label_kind IN ('lemma','synonym','definition','translation')),
  is_machine   boolean NOT NULL DEFAULT false,
  quality      smallint CHECK (quality BETWEEN 0 AND 100),
  source_id    integer REFERENCES public.source(id),
  batch_id     uuid REFERENCES staging.import_batch(id),
  UNIQUE (concept_id, language_id, rank, label_kind)
);

CREATE INDEX concept_label_lookup ON core.concept_label (language_id, text);
CREATE INDEX concept_label_concept ON core.concept_label (concept_id, language_id, rank);
