-- M12.1: account privacy evidence and manual data-rights workflow.
CREATE TABLE app.privacy_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  request_id uuid NOT NULL,
  purpose_id text NOT NULL CHECK (purpose_id IN ('ai_assistance','online_translation','analytics')),
  action text NOT NULL CHECK (action IN ('grant','withdraw')),
  notice_version text NOT NULL CHECK (length(notice_version) BETWEEN 1 AND 80),
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  UNIQUE (user_id, request_id)
);
CREATE INDEX privacy_event_current ON app.privacy_event(user_id,purpose_id,id DESC);
CREATE TABLE app.privacy_request (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  request_id uuid NOT NULL,
  kind text NOT NULL CHECK (kind IN ('access','rectification','erasure','restriction','objection')),
  status text NOT NULL DEFAULT 'received' CHECK (status IN ('received','in_progress','rejected','completed')),
  received_at timestamptz(6) NOT NULL DEFAULT now(),
  acknowledged_at timestamptz(6) NOT NULL DEFAULT now(),
  target_at timestamptz(6) NOT NULL,
  updated_at timestamptz(6) NOT NULL DEFAULT now(),
  updated_by bigint REFERENCES app.users(id) ON DELETE SET NULL,
  resolution_reference uuid,
  rejection_reason text CHECK (rejection_reason IN ('identity_unverified','outside_scope','duplicate')),
  UNIQUE(user_id,request_id),
  CHECK ((status = 'rejected') = (rejection_reason IS NOT NULL)),
  CHECK ((status = 'completed') = (resolution_reference IS NOT NULL))
);
CREATE INDEX privacy_request_queue ON app.privacy_request(status,received_at,id);
