  ('streak_day',   'Duy trì ngày học có ôn tập',   2, 2)
ON CONFLICT (code) DO NOTHING;

CREATE TABLE app.xp_event (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  amount          integer NOT NULL CHECK (amount <> 0),
  source          text NOT NULL
                  CHECK (source IN ('review', 'quiz', 'streak', 'achievement',
                                    'correction', 'manual')),
  ref_kind        text,
  ref_id          text,
  idempotency_key text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, idempotency_key)
);
CREATE INDEX xp_event_by_user ON app.xp_event (user_id, created_at DESC);
CREATE INDEX xp_event_by_source ON app.xp_event (source, created_at DESC);

CREATE TABLE app.streak_day (
  user_id      bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  day          date NOT NULL,
  review_count integer NOT NULL DEFAULT 0 CHECK (review_count >= 0),
  xp           integer NOT NULL DEFAULT 0,
  met_goal     boolean NOT NULL DEFAULT false,
  PRIMARY KEY (user_id, day)
);
CREATE INDEX streak_day_recent ON app.streak_day (user_id, day DESC);

CREATE TABLE app.user_stats (
  user_id         bigint PRIMARY KEY REFERENCES app.users(id) ON DELETE CASCADE,
  xp_total        bigint NOT NULL DEFAULT 0 CHECK (xp_total >= 0),
  level           integer NOT NULL DEFAULT 1 CHECK (level > 0),
  streak_current  integer NOT NULL DEFAULT 0 CHECK (streak_current >= 0),
  streak_longest  integer NOT NULL DEFAULT 0 CHECK (streak_longest >= 0),
  last_study_date date,
  items_learned   integer NOT NULL DEFAULT 0 CHECK (items_learned >= 0),
  reviews_total   integer NOT NULL DEFAULT 0 CHECK (reviews_total >= 0),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER user_stats_touch BEFORE UPDATE ON app.user_stats
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

CREATE TABLE app.achievement (
  code        text PRIMARY KEY,
  name_vi     text NOT NULL,
  description text,
  icon        text,
  category    text NOT NULL CHECK (category IN ('milestone', 'streak', 'quiz', 'social')),
  rule        jsonb NOT NULL CHECK (jsonb_typeof(rule) = 'object'),
  xp_reward   integer NOT NULL DEFAULT 0 CHECK (xp_reward >= 0),
  is_active   boolean NOT NULL DEFAULT true
);

