CREATE TABLE app.user_achievement (
  user_id          bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  achievement_code text NOT NULL REFERENCES app.achievement(code) ON DELETE CASCADE,
  progress         numeric(10, 2) NOT NULL DEFAULT 0 CHECK (progress >= 0),
  unlocked_at      timestamptz,
  seen_at          timestamptz,
  PRIMARY KEY (user_id, achievement_code)
);
CREATE INDEX user_achievement_unseen
  ON app.user_achievement (user_id) WHERE unlocked_at IS NOT NULL AND seen_at IS NULL;

-- Bảng xếp hạng tuần (Phase 2): tổng hợp từ xp_event theo cron, DB chỉ giữ snapshot.
CREATE TABLE app.leaderboard_snapshot (
  period_start date NOT NULL,
  scope        text NOT NULL DEFAULT 'global',
  user_id      bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  xp           integer NOT NULL,
  rank         integer NOT NULL CHECK (rank > 0),
  computed_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (period_start, scope, user_id)
);
CREATE INDEX leaderboard_top ON app.leaderboard_snapshot (period_start, scope, rank);
