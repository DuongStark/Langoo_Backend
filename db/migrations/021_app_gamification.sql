-- 019_app_gamification.sql — XP, streak, thành tích, bảng xếp hạng.
--
-- Nguyên tắc: xp_event / streak_day là sổ cái append-only (nguồn sự thật);
-- user_stats chỉ là cache denormalize, rebuild được từ log nếu sai.
-- idempotency_key chống cộng trùng khi client retry.
-- "Ngày" của streak tính theo timezone người dùng (app.user_settings.timezone),
-- không phải UTC — service truyền ngày đã quy đổi khi ghi.

CREATE TABLE app.xp_rule (
  code        text PRIMARY KEY,
  description text NOT NULL,
  amount      integer NOT NULL CHECK (amount <> 0),
  daily_cap   integer CHECK (daily_cap IS NULL OR daily_cap > 0),
  is_active   boolean NOT NULL DEFAULT true,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

