-- 006_core_lexeme_forms.sql — quan hệ entry JMdict với dạng viết/cách đọc.
-- 005_core.sql giữ bản sao JSONB để tái dựng dữ liệu nguồn; các bảng dưới
-- đây là quan hệ chuẩn dùng cho truy vấn và khóa ngoại.

-- Một lexeme có thể có nhiều dạng kanji và nhiều dạng kana.
CREATE TABLE core.lexeme_form (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lexeme_id   bigint NOT NULL REFERENCES core.lexeme(id) ON DELETE RESTRICT,
  kind        text NOT NULL CHECK (kind IN ('kanji', 'kana')),
  form_text   text NOT NULL CHECK (btrim(form_text) <> ''),
  form_order  smallint NOT NULL CHECK (form_order > 0),
  is_common   boolean NOT NULL DEFAULT false,
  attributes  jsonb NOT NULL DEFAULT '{}'::jsonb
              CHECK (jsonb_typeof(attributes) = 'object'),
  source_id   integer REFERENCES public.source(id),
  batch_id    uuid REFERENCES staging.import_batch(id),
  CONSTRAINT lexeme_form_text_unique UNIQUE (lexeme_id, kind, form_text),
  CONSTRAINT lexeme_form_order_unique UNIQUE (lexeme_id, kind, form_order)
);
CREATE INDEX lexeme_form_lookup
  ON core.lexeme_form (kind, form_text, lexeme_id);
CREATE INDEX lexeme_form_by_lexeme
  ON core.lexeme_form (lexeme_id, kind, form_order);

-- Tag gốc gắn trên từng dạng, ví dụ search-only, irregular kana, ateji.
CREATE TABLE core.lexeme_form_tag (
  form_id  bigint NOT NULL REFERENCES core.lexeme_form(id) ON DELETE CASCADE,
  tag_code text NOT NULL REFERENCES public.tag(code),
  PRIMARY KEY (form_id, tag_code)
);
CREATE INDEX lexeme_form_tag_code
  ON core.lexeme_form_tag (tag_code, form_id);

-- Kana có thể chỉ áp dụng cho một số dạng kanji trong cùng entry. Wildcard
-- (*) được mở rộng thành các dòng cụ thể bởi importer; payload gốc vẫn giữ
-- wildcard trong lexeme_form.attributes.
CREATE TABLE core.lexeme_form_applies_to (
  form_id        bigint NOT NULL REFERENCES core.lexeme_form(id) ON DELETE CASCADE,
  target_form_id bigint NOT NULL REFERENCES core.lexeme_form(id) ON DELETE CASCADE,
  PRIMARY KEY (form_id, target_form_id),
  CONSTRAINT form_applies_to_different_kind CHECK (form_id <> target_form_id)
);
CREATE INDEX lexeme_form_applies_target
  ON core.lexeme_form_applies_to (target_form_id, form_id);

-- JMdict có appliesToKanji/appliesToKana trên từng sense. Importer mở rộng
-- wildcard thành các form cụ thể để truy vấn sense nào dùng dạng nào.
CREATE TABLE core.sense_form (
  sense_id bigint NOT NULL REFERENCES core.sense(id) ON DELETE CASCADE,
  form_id  bigint NOT NULL REFERENCES core.lexeme_form(id) ON DELETE CASCADE,
  PRIMARY KEY (sense_id, form_id)
);
CREATE INDEX sense_form_by_form ON core.sense_form (form_id, sense_id);

-- Một form kanji là chuỗi nhiều ký tự. Bảng này liên kết từng ký tự có trong
-- KANJIDIC2 với vị trí Unicode trong chuỗi; ký tự chưa có trong KANJIDIC2
-- không tạo dòng và vẫn được giữ trong form_text.
CREATE TABLE core.lexeme_form_kanji_char (
  form_id       bigint NOT NULL REFERENCES core.lexeme_form(id) ON DELETE CASCADE,
  char_position integer NOT NULL CHECK (char_position > 0),
  kanji_literal text NOT NULL REFERENCES core.kanji(literal) ON DELETE RESTRICT,
  PRIMARY KEY (form_id, char_position),
  CONSTRAINT kanji_char_is_single_codepoint CHECK (char_length(kanji_literal) = 1)
);
CREATE INDEX lexeme_form_kanji_char_by_literal
  ON core.lexeme_form_kanji_char (kanji_literal, form_id);
