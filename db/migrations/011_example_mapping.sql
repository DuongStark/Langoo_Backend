-- Liên kết ví dụ source với câu canonical và nghĩa/concept nhiều-nhiều.

CREATE TABLE core.example_annotation (
  id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_example_id          bigint NOT NULL UNIQUE REFERENCES core.example(id) ON DELETE RESTRICT,
  canonical_example_id       bigint REFERENCES core.example(id) ON DELETE RESTRICT,
  source_sentence_id         bigint,
  match_text                 text,
  embedded_sentence          text,
  embedded_translation       text,
  match_status               text NOT NULL DEFAULT 'pending'
                             CHECK (match_status IN (
                               'matched','missing_snapshot','text_mismatch','pending','rejected')),
  match_reason               text,
  evidence                   jsonb NOT NULL DEFAULT '{}'::jsonb
                             CHECK (jsonb_typeof(evidence) = 'object'),
  mapping_run_id             bigint REFERENCES core.mapping_run(id),
  source_id                  integer REFERENCES public.source(id),
  batch_id                   uuid REFERENCES staging.import_batch(id),
  CONSTRAINT example_annotation_not_self
    CHECK (canonical_example_id IS NULL OR canonical_example_id <> source_example_id)
);

CREATE INDEX example_annotation_canonical
  ON core.example_annotation (canonical_example_id)
  WHERE canonical_example_id IS NOT NULL;
CREATE INDEX example_annotation_status
  ON core.example_annotation (match_status, source_sentence_id);

CREATE TABLE core.example_sense (
  example_id    bigint NOT NULL REFERENCES core.example(id) ON DELETE RESTRICT,
  sense_id      bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  relation      text NOT NULL DEFAULT 'illustrates'
                CHECK (relation IN ('illustrates','candidate','rejected')),
  confidence    real CHECK (confidence >= 0 AND confidence <= 1),
  method        text NOT NULL CHECK (btrim(method) <> ''),
  verified      boolean NOT NULL DEFAULT false,
  mapping_run_id bigint REFERENCES core.mapping_run(id),
  evidence      jsonb NOT NULL DEFAULT '{}'::jsonb
                CHECK (jsonb_typeof(evidence) = 'object'),
  PRIMARY KEY (example_id, sense_id)
);

CREATE INDEX example_sense_by_sense ON core.example_sense (sense_id, confidence DESC);

CREATE TABLE core.example_concept (
  example_id     bigint NOT NULL REFERENCES core.example(id) ON DELETE RESTRICT,
  concept_id     bigint NOT NULL REFERENCES core.concept(id) ON DELETE RESTRICT,
  confidence     real CHECK (confidence >= 0 AND confidence <= 1),
  method         text NOT NULL CHECK (btrim(method) <> ''),
  verified       boolean NOT NULL DEFAULT false,
  mapping_run_id bigint REFERENCES core.mapping_run(id),
  evidence       jsonb NOT NULL DEFAULT '{}'::jsonb
                 CHECK (jsonb_typeof(evidence) = 'object'),
  PRIMARY KEY (example_id, concept_id)
);

CREATE INDEX example_concept_by_concept ON core.example_concept (concept_id, confidence DESC);
