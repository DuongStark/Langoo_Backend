-- 021_app_ai.sql — AI chatbot và AI quiz.
--
-- Lượt làm quiz KHÔNG có bảng riêng: dùng app.study_session (kind='quiz',
-- quiz_id) + app.study_session_item (quiz_question_id) để điểm, thời gian và
-- câu sai nằm chung một mô hình với các chế độ ôn khác.
-- FK của study_session.quiz_id / session_item.quiz_question_id được thêm ở
-- cuối file này vì bảng quiz tạo sau study_session (migration 020).

CREATE TABLE app.chat_session (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  profile_id     uuid REFERENCES app.study_profile(id) ON DELETE SET NULL,
  language_id    smallint NOT NULL REFERENCES public.language(id),
  scenario       text,
  title          text,
  model          text,
  prompt_version text,
  summary        text,
  message_count  integer NOT NULL DEFAULT 0 CHECK (message_count >= 0),
  last_message_at timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  archived_at    timestamptz
);
CREATE INDEX chat_session_by_user
  ON app.chat_session (user_id, last_message_at DESC NULLS LAST);

CREATE TABLE app.chat_message (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id   uuid NOT NULL REFERENCES app.chat_session(id) ON DELETE CASCADE,
  role         text NOT NULL CHECK (role IN ('system', 'user', 'assistant', 'tool')),
  content      text NOT NULL CHECK (btrim(content) <> ''),
  content_json jsonb NOT NULL DEFAULT '{}'::jsonb
               CHECK (jsonb_typeof(content_json) = 'object'),
  ref_sense_id bigint REFERENCES core.sense(id) ON DELETE SET NULL,
  tokens_in    integer CHECK (tokens_in >= 0),
  tokens_out   integer CHECK (tokens_out >= 0),
  cost_usd     numeric(10, 6) CHECK (cost_usd >= 0),
  model        text,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX chat_message_by_session ON app.chat_message (session_id, created_at);

-- Quota + chi phí theo kỳ (period = ngày đầu kỳ đang đếm; dev có thể dùng ngày,
-- production có thể dùng đầu tháng — service quyết định và ghi rõ).
CREATE TABLE app.ai_usage (
  user_id       bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  period        date NOT NULL,
  feature       text NOT NULL CHECK (feature IN ('chat', 'quiz', 'embedding', 'other')),
  request_count integer NOT NULL DEFAULT 0 CHECK (request_count >= 0),
  tokens_in     bigint NOT NULL DEFAULT 0 CHECK (tokens_in >= 0),
  tokens_out    bigint NOT NULL DEFAULT 0 CHECK (tokens_out >= 0),
  cost_usd      numeric(12, 6) NOT NULL DEFAULT 0 CHECK (cost_usd >= 0),
  PRIMARY KEY (user_id, period, feature)
);

CREATE TABLE app.quiz (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  profile_id     uuid NOT NULL REFERENCES app.study_profile(id) ON DELETE CASCADE,
  collection_id  uuid REFERENCES app.collection(id) ON DELETE SET NULL,
  quiz_type      text NOT NULL CHECK (quiz_type IN ('multiple_choice', 'fill_blank',
                                                    'matching', 'mixed')),
  difficulty     text NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard')),
  question_count smallint NOT NULL CHECK (question_count BETWEEN 1 AND 50),
  generator      jsonb NOT NULL DEFAULT '{}'::jsonb
                 CHECK (jsonb_typeof(generator) = 'object'),
  status         text NOT NULL DEFAULT 'ready'
                 CHECK (status IN ('generating', 'ready', 'failed', 'expired')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  expires_at     timestamptz
);
CREATE INDEX quiz_by_user ON app.quiz (user_id, created_at DESC);

CREATE TABLE app.quiz_question (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id       uuid NOT NULL REFERENCES app.quiz(id) ON DELETE CASCADE,
  ordinal       smallint NOT NULL CHECK (ordinal > 0),
  question_type text NOT NULL CHECK (question_type IN ('multiple_choice',
                                                       'fill_blank', 'matching')),
  prompt        text NOT NULL CHECK (btrim(prompt) <> ''),
  options       jsonb NOT NULL DEFAULT '[]'::jsonb
                CHECK (jsonb_typeof(options) = 'array'),
  correct_answer jsonb NOT NULL,
  explanation   text,
  language_id   smallint REFERENCES public.language(id),
  concept_id    bigint REFERENCES core.concept(id) ON DELETE SET NULL,
  item_id       uuid REFERENCES app.collection_item(id) ON DELETE SET NULL,
  UNIQUE (quiz_id, ordinal)
);

-- FK bổ sung: lượt làm quiz trỏ tới bộ câu hỏi, từng câu trả lời trỏ tới câu hỏi.
ALTER TABLE app.study_session
  ADD CONSTRAINT study_session_quiz_fk
  FOREIGN KEY (quiz_id) REFERENCES app.quiz(id) ON DELETE SET NULL;

ALTER TABLE app.study_session_item
  ADD CONSTRAINT session_item_quiz_question_fk
  FOREIGN KEY (quiz_question_id) REFERENCES app.quiz_question(id) ON DELETE SET NULL;
