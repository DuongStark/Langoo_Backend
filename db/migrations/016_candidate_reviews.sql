-- Lưu nhiều lượt đánh giá cho cùng một candidate mà không ghi đè kết quả trước.
-- Candidate vẫn giữ quyết định cuối cùng; bảng này chỉ là provenance của review.

CREATE TABLE core.sense_concept_candidate_review (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id   bigint NOT NULL
                 REFERENCES core.sense_concept_candidate(id) ON DELETE RESTRICT,
  mapping_run_id bigint NOT NULL
                 REFERENCES core.mapping_run(id) ON DELETE RESTRICT,
  reviewer_kind  text NOT NULL
                 CHECK (reviewer_kind IN ('llm','human','rule')),
  reviewer       text NOT NULL CHECK (btrim(reviewer) <> ''),
  question_type  text NOT NULL CHECK (btrim(question_type) <> ''),
  prompt_version text,
  relation       text
                 CHECK (relation IS NULL OR relation IN
                   ('exact','broader','narrower','related','none','uncertain')),
  score          real CHECK (score IS NULL OR (score >= 0 AND score <= 1)),
  result         jsonb NOT NULL DEFAULT '{}'::jsonb
                 CHECK (jsonb_typeof(result) = 'object'),
  artifact_hash  text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (candidate_id, mapping_run_id, reviewer_kind, reviewer)
);

CREATE INDEX sense_concept_candidate_review_candidate
  ON core.sense_concept_candidate_review
     (candidate_id, created_at DESC);

CREATE INDEX sense_concept_candidate_review_run
  ON core.sense_concept_candidate_review
     (mapping_run_id, reviewer_kind, score DESC);

COMMENT ON TABLE core.sense_concept_candidate_review IS
  'Các lượt LLM/người/quy tắc đánh giá candidate; không thay thế quyết định cuối ở candidate.';
