-- 022_core_reference.sql — bảng tham chiếu nội dung còn thiếu cho app:
-- nghĩa bộ thủ, media (thứ tự nét), và bộ từ hệ thống (deck).
--
-- Additive hoàn toàn: không sửa dữ liệu đã nạp ở 001–014. FK từ app.collection
-- và app.collection_item sang core.deck được thêm ở cuối file (trước đó hai
-- cột này giữ dạng bigint trần trong 018).

-- ============ bộ thủ Kangxi (214 bộ) ============
-- Dữ liệu tĩnh: join với kanji.radical_classical (số bộ) và
-- kanji_radical.part (theo character/variants). Seed 214 dòng sẽ bổ sung ở
-- bước nội dung; khi chưa seed, UI dùng LEFT JOIN và chịu NULL.
CREATE TABLE public.radical (
  number       smallint PRIMARY KEY CHECK (number BETWEEN 1 AND 214),
  character    text NOT NULL UNIQUE CHECK (char_length(character) = 1),
  name_en      text,
  name_vi      text,
  meaning_vi   text,
  stroke_count smallint CHECK (stroke_count > 0),
  variants     text[] NOT NULL DEFAULT '{}'
);
COMMENT ON COLUMN public.radical.variants IS
  'Biến thể đồ họa của bộ (ví dụ 心 → 忄, 㣺) để join với kanji_radical.part.';

-- ============ media dùng chung ============
-- object_key trỏ tới object storage, KHÔNG lưu blob trong DB.
CREATE TABLE core.media_asset (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       text NOT NULL CHECK (kind IN ('stroke_svg', 'stroke_gif', 'audio_tts')),
  object_key text NOT NULL UNIQUE CHECK (btrim(object_key) <> ''),
  mime       text NOT NULL,
  bytes      integer CHECK (bytes > 0),
  sha256     text,
  provider   text,
  source_id  integer REFERENCES public.source(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX media_asset_by_kind ON core.media_asset (kind);

CREATE TABLE core.kanji_media (
  kanji_literal text NOT NULL REFERENCES core.kanji(literal) ON DELETE CASCADE,
  asset_id      bigint NOT NULL REFERENCES core.media_asset(id) ON DELETE RESTRICT,
  kind          text NOT NULL CHECK (kind IN ('stroke_svg', 'stroke_gif')),
  frame_count   smallint CHECK (frame_count > 0),
  PRIMARY KEY (kanji_literal, kind)
);

-- ============ bộ từ hệ thống (nội dung biên soạn sẵn) ============
-- Ghim ở cấp nghĩa (anchor_sense_id) + concept khi có, để lọc/cặp ngôn ngữ.
CREATE TABLE core.deck (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug         text NOT NULL UNIQUE CHECK (btrim(slug) <> ''),
  title        text NOT NULL CHECK (btrim(title) <> ''),
  description  text,
  language_id  smallint NOT NULL REFERENCES public.language(id),
  level_label  text,
  is_published boolean NOT NULL DEFAULT false,
  item_count   integer NOT NULL DEFAULT 0 CHECK (item_count >= 0),
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX deck_published ON core.deck (language_id, level_label)
  WHERE is_published;

CREATE TABLE core.deck_item (
  deck_id         bigint NOT NULL REFERENCES core.deck(id) ON DELETE CASCADE,
  anchor_sense_id bigint NOT NULL REFERENCES core.sense(id) ON DELETE RESTRICT,
  concept_id      bigint REFERENCES core.concept(id) ON DELETE RESTRICT,
  position        integer NOT NULL CHECK (position > 0),
  PRIMARY KEY (deck_id, anchor_sense_id)
);
CREATE INDEX deck_item_position ON core.deck_item (deck_id, position);
CREATE INDEX deck_item_concept ON core.deck_item (concept_id)
  WHERE concept_id IS NOT NULL;

-- ============ FK trễ từ tầng app sang deck ============
ALTER TABLE app.collection
  ADD CONSTRAINT collection_cloned_deck_fk
  FOREIGN KEY (cloned_from_deck_id) REFERENCES core.deck(id) ON DELETE SET NULL;

ALTER TABLE app.collection_item
  ADD CONSTRAINT collection_item_deck_fk
  FOREIGN KEY (added_from_deck_id) REFERENCES core.deck(id) ON DELETE SET NULL;
