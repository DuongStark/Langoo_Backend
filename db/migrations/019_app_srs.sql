-- 017_app_srs.sql — trạng thái ôn tập ngắt quãng (SRS) và nhật ký ôn.
--
-- Tách trạng thái theo MẶT ngôn ngữ (face) và theo CHIỀU (recognize/recall):
-- biết "apple" không có nghĩa là biết "りんご". user_id/profile_id được
-- denormalize trên srs_state để index "thẻ đến hạn của tôi" không phải join.
--
-- review_log là append-only, partition theo tháng; srs_state là cache tính lại
-- được. Khi srs_state vượt ~50 triệu dòng mới partition HASH theo face_id
-- (khoá duy nhất (face_id, direction) đã chứa partition key nên giữ nguyên).

CREATE TABLE app.srs_state (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  face_id        uuid NOT NULL REFERENCES app.collection_item_face(id) ON DELETE CASCADE,
  user_id        bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  profile_id     uuid NOT NULL REFERENCES app.study_profile(id) ON DELETE CASCADE,
  direction      text NOT NULL CHECK (direction IN ('recognize', 'recall')),
  state          text NOT NULL DEFAULT 'new'
                 CHECK (state IN ('new', 'learning', 'review', 'relearning')),
  due_at         timestamptz NOT NULL DEFAULT now(),
  stability      real CHECK (stability > 0),
  difficulty     real CHECK (difficulty > 0),
  reps           integer NOT NULL DEFAULT 0 CHECK (reps >= 0),
  lapses         integer NOT NULL DEFAULT 0 CHECK (lapses >= 0),
  scheduled_days integer CHECK (scheduled_days >= 0),
  elapsed_days   integer CHECK (elapsed_days >= 0),
  last_review_at timestamptz,
  suspended      boolean NOT NULL DEFAULT false,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (face_id, direction)
);
-- Index chính của toàn app: "cho tôi N thẻ đến hạn".
CREATE INDEX srs_due_by_user ON app.srs_state (user_id, due_at)
  WHERE NOT suspended;
CREATE INDEX srs_due_by_profile ON app.srs_state (profile_id, due_at)
  WHERE NOT suspended;
CREATE TRIGGER srs_state_touch BEFORE UPDATE ON app.srs_state
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

-- rating: 1 = Again, 2 = Hard, 3 = Good, 4 = Easy.
-- srs_id ON DELETE SET NULL để lịch sử ôn không mất khi face bị xoá; face_id
-- giữ nguyên trên log để thống kê.
CREATE TABLE app.review_log (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  srs_id      bigint REFERENCES app.srs_state(id) ON DELETE SET NULL,
  user_id     bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  face_id     uuid NOT NULL,
  rating      smallint NOT NULL CHECK (rating BETWEEN 1 AND 4),
  mode        text NOT NULL DEFAULT 'flashcard'
              CHECK (mode IN ('flashcard', 'multiple_choice', 'matching',
                              'typing', 'listening')),
  elapsed_ms  integer CHECK (elapsed_ms >= 0),
  reviewed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, reviewed_at)
) PARTITION BY RANGE (reviewed_at);

CREATE INDEX review_log_by_user ON app.review_log (user_id, reviewed_at DESC);

-- Tạo partition tháng nếu chưa có; gọi từ cron/CLI trước mỗi tháng mới.
CREATE FUNCTION app.ensure_month_partition(p_month date) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  v_start date := date_trunc('month', p_month)::date;
  v_end   date := (v_start + interval '1 month')::date;
  v_name  text := 'review_log_' || to_char(v_start, 'YYYY_MM');
BEGIN
  IF to_regclass('app.' || v_name) IS NULL THEN
    EXECUTE format(
      'CREATE TABLE app.%I PARTITION OF app.review_log FOR VALUES FROM (%L) TO (%L)',
      v_name, v_start, v_end);
  END IF;
  RETURN v_name;
END;
$$;

-- Tạo sẵn 3 năm partition đầu (2026-09 → 2029-08) để insert không bao giờ lỗi;
-- các tháng sau do job gọi app.ensure_month_partition().
DO $$
DECLARE
  m date := date '2026-09-01';
BEGIN
  WHILE m < date '2029-09-01' LOOP
    PERFORM app.ensure_month_partition(m);
    m := m + interval '1 month';
  END LOOP;
END $$;
