-- 020_app_reminders.sql — nhắc nhở học hằng ngày và log gửi thông báo.
--
-- next_fire_at tính sẵn theo UTC từ time_of_day + timezone + weekdays để worker
-- chỉ quét một index. Worker @nestjs/schedule chạy mỗi phút:
--   SELECT ... WHERE is_enabled AND next_fire_at <= now() FOR UPDATE SKIP LOCKED
-- gửi qua FCM/APNs (app.device) hoặc email, ghi notification_log, rồi tính
-- lại next_fire_at kế tiếp.
-- Giờ địa phương có thể đổi theo DST → lưu timezone, không lưu offset cố định.

CREATE TABLE app.reminder (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id               bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  label                 text,
  time_of_day           time NOT NULL,
  timezone              text NOT NULL,
  weekdays              smallint[] NOT NULL DEFAULT '{1,2,3,4,5,6,7}'
                        CHECK (weekdays <@ ARRAY[1,2,3,4,5,6,7]::smallint[]),
  channels              text[] NOT NULL DEFAULT '{push}'
                        CHECK (channels <@ ARRAY['push','email']::text[]),
  is_enabled            boolean NOT NULL DEFAULT true,
  smart_reminder        boolean NOT NULL DEFAULT false,
  missed_days_threshold smallint NOT NULL DEFAULT 2
                        CHECK (missed_days_threshold BETWEEN 1 AND 30),
  next_fire_at          timestamptz,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX reminder_due ON app.reminder (next_fire_at)
  WHERE is_enabled AND next_fire_at IS NOT NULL;
CREATE INDEX reminder_by_user ON app.reminder (user_id);
CREATE TRIGGER reminder_touch BEFORE UPDATE ON app.reminder
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

CREATE TABLE app.notification_log (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  reminder_id         uuid REFERENCES app.reminder(id) ON DELETE SET NULL,
  channel             text NOT NULL CHECK (channel IN ('push', 'email')),
  title               text,
  body                text,
  payload             jsonb NOT NULL DEFAULT '{}'::jsonb
                      CHECK (jsonb_typeof(payload) = 'object'),
  provider_message_id text,
  status              text NOT NULL DEFAULT 'queued'
                      CHECK (status IN ('queued', 'sent', 'failed', 'opened', 'clicked')),
  error               text,
  idempotency_key     text,
  sent_at             timestamptz,
  opened_at           timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT notification_queued_has_no_sent_at CHECK (
    sent_at IS NULL OR status <> 'queued'
  )
);
CREATE INDEX notification_log_by_user ON app.notification_log (user_id, created_at DESC);
CREATE UNIQUE INDEX notification_log_idempotent
  ON app.notification_log (reminder_id, idempotency_key)
  WHERE reminder_id IS NOT NULL AND idempotency_key IS NOT NULL;
