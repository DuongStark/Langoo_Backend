-- 018_app_sessions.sql — phiên ôn tập/quiz và từng câu trả lời.
--
-- Một mô hình phiên dùng chung cho ôn theo bộ (F4) và AI quiz (F7):
-- study_session.kind = 'review' | 'practice' | 'quiz'.
-- kind='quiz' trỏ tới app.quiz qua cột quiz_id (FK được thêm ở 023_app_ai.sql
-- vì bảng quiz tạo sau). Từng câu trả lời nằm ở study_session_item; màn hình
-- "câu sai" và thống kê đọc từ đây.

CREATE TABLE app.study_session (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  profile_id    uuid NOT NULL REFERENCES app.study_profile(id) ON DELETE CASCADE,
  kind          text NOT NULL CHECK (kind IN ('review', 'practice', 'quiz')),
  mode          text NOT NULL CHECK (mode IN ('flashcard', 'multiple_choice',
                                              'matching', 'typing', 'listening')),
  collection_id uuid REFERENCES app.collection(id) ON DELETE SET NULL,
  quiz_id       uuid,
  settings      jsonb NOT NULL DEFAULT '{}'::jsonb
                CHECK (jsonb_typeof(settings) = 'object'),
  status        text NOT NULL DEFAULT 'in_progress'
                CHECK (status IN ('in_progress', 'completed', 'abandoned')),
  item_count    integer NOT NULL DEFAULT 0 CHECK (item_count >= 0),
  correct_count integer NOT NULL DEFAULT 0 CHECK (correct_count >= 0),
  score         integer CHECK (score BETWEEN 0 AND 100),
  xp_awarded    integer NOT NULL DEFAULT 0,
  started_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz,
  CONSTRAINT study_session_quiz_needs_quiz CHECK (kind <> 'quiz' OR quiz_id IS NOT NULL),
  CONSTRAINT study_session_correct_le_items CHECK (correct_count <= item_count)
);
CREATE INDEX study_session_by_user ON app.study_session (user_id, started_at DESC);
CREATE INDEX study_session_by_profile
  ON app.study_session (profile_id, started_at DESC);
CREATE INDEX study_session_open
  ON app.study_session (user_id) WHERE status = 'in_progress';

-- prompt/correct_answer là snapshot câu hỏi để màn hình lịch sử hiện lại được
-- kể cả khi dữ liệu nguồn đổi. user_answer giữ nguyên văn câu trả lời.
CREATE TABLE app.study_session_item (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id       uuid NOT NULL REFERENCES app.study_session(id) ON DELETE CASCADE,
  ordinal          smallint NOT NULL CHECK (ordinal > 0),
  srs_id           bigint REFERENCES app.srs_state(id) ON DELETE SET NULL,
  face_id          uuid REFERENCES app.collection_item_face(id) ON DELETE SET NULL,
  quiz_question_id bigint,
  prompt           jsonb NOT NULL DEFAULT '{}'::jsonb
                   CHECK (jsonb_typeof(prompt) = 'object'),
  correct_answer   jsonb,
  user_answer      jsonb,
  is_correct       boolean,
  rating           smallint CHECK (rating BETWEEN 1 AND 4),
  elapsed_ms       integer CHECK (elapsed_ms >= 0),
  answered_at      timestamptz,
  CONSTRAINT session_item_has_source CHECK (
    srs_id IS NOT NULL OR quiz_question_id IS NOT NULL OR prompt <> '{}'::jsonb
  ),
  UNIQUE (session_id, ordinal)
);
CREATE INDEX session_item_by_session ON app.study_session_item (session_id, ordinal);
CREATE INDEX session_item_wrong
  ON app.study_session_item (session_id) WHERE is_correct IS FALSE;
