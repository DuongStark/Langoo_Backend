-- 015_app_users_auth.sql — tầng người học (schema app): tài khoản, phiên đăng nhập,
-- thiết bị, hồ sơ học, lịch sử tra cứu và báo lỗi nghĩa.
--
-- Schema app là write-heavy và tách khỏi core (read-heavy) về cả vòng đời lẫn
-- connection pool. Mọi bảng cascade theo app.users để phục vụ xoá dữ liệu theo
-- người. PK kiểu uuid trên thực thể client-visible là uuid v7 do ứng dụng sinh;
-- DEFAULT gen_random_uuid() (v4) chỉ là lưới an toàn cho thử nghiệm thủ công.
-- Không dùng citext vì PostgreSQL nhúng không có extension; chuẩn hoá email
-- bằng unique index trên lower(email).

CREATE SCHEMA app;

-- Hàm dùng chung: tự cập nhật cột updated_at khi UPDATE.
CREATE FUNCTION app.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- ============ người dùng & xác thực ============

CREATE TABLE app.users (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL CHECK (btrim(email) <> ''),
  display_name  text,
  avatar_url    text,
  status        text NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'locked', 'deleted')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  deleted_at    timestamptz
);
CREATE UNIQUE INDEX users_email_unique ON app.users (lower(email));
CREATE INDEX users_by_status ON app.users (status) WHERE status <> 'active';

-- Tách khỏi users để thêm SSO không sửa bảng users. Chỉ một dòng mang mật khẩu
-- cho mỗi tài khoản; provider_uid là id phía nhà cung cấp.
CREATE TABLE app.user_identity (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  provider          text NOT NULL
                    CHECK (provider IN ('password', 'google', 'apple')),
  provider_uid      text NOT NULL CHECK (btrim(provider_uid) <> ''),
  password_hash     text,
  email_verified_at timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_uid),
  CONSTRAINT user_identity_password_shape CHECK (
    (provider = 'password' AND password_hash IS NOT NULL) OR
    (provider <> 'password' AND password_hash IS NULL)
  )
);
CREATE INDEX user_identity_by_user ON app.user_identity (user_id);

-- Token đẩy thông báo phải thu hồi được: FCM trả "unregistered" thì set
-- revoked_at rồi đăng ký token mới. Vì vậy unique chỉ áp trên token còn sống.
CREATE TABLE app.device (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  platform      text NOT NULL CHECK (platform IN ('ios', 'android', 'web')),
  push_provider text CHECK (push_provider IN ('fcm', 'apns', 'webpush')),
  push_token    text,
  app_version   text,
  last_seen_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  revoked_at    timestamptz,
  CONSTRAINT device_push_pair CHECK (
    (push_provider IS NULL AND push_token IS NULL) OR
    (push_provider IS NOT NULL AND push_token IS NOT NULL)
  )
);
CREATE UNIQUE INDEX device_push_unique
  ON app.device (push_provider, push_token)
  WHERE push_token IS NOT NULL AND revoked_at IS NULL;
CREATE INDEX device_by_user ON app.device (user_id);

-- JWT access token ngắn hạn không cần bảng; đây là refresh session.
CREATE TABLE app.user_session (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id            bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  device_id          uuid REFERENCES app.device(id) ON DELETE SET NULL,
  refresh_token_hash text NOT NULL UNIQUE CHECK (btrim(refresh_token_hash) <> ''),
  created_at         timestamptz NOT NULL DEFAULT now(),
  last_used_at       timestamptz,
  expires_at         timestamptz NOT NULL,
  revoked_at         timestamptz
);
CREATE INDEX user_session_active
  ON app.user_session (user_id, expires_at) WHERE revoked_at IS NULL;

-- ============ hồ sơ học ============
-- Một "khoá học": en→vi hoặc ja→vi; chế độ song ngữ chỉ là việc
-- secondary_language_id khác NULL. Mọi dữ liệu học tập gắn profile_id.

CREATE TABLE app.study_profile (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id               bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  name                  text NOT NULL CHECK (btrim(name) <> ''),
  primary_language_id   smallint NOT NULL REFERENCES public.language(id),
  secondary_language_id smallint REFERENCES public.language(id),
  support_language_id   smallint NOT NULL REFERENCES public.language(id),
  is_default            boolean NOT NULL DEFAULT false,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT study_profile_languages_differ CHECK (
    (secondary_language_id IS NULL OR secondary_language_id <> primary_language_id) AND
    support_language_id <> primary_language_id AND
    (secondary_language_id IS NULL OR support_language_id <> secondary_language_id)
  )
);
CREATE UNIQUE INDEX study_profile_one_default
  ON app.study_profile (user_id) WHERE is_default;
CREATE INDEX study_profile_by_user ON app.study_profile (user_id);
CREATE TRIGGER study_profile_touch BEFORE UPDATE ON app.study_profile
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

CREATE TABLE app.user_settings (
  user_id           bigint PRIMARY KEY REFERENCES app.users(id) ON DELETE CASCADE,
  timezone          text NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
  ui_language_id    smallint REFERENCES public.language(id),
  daily_goal        smallint NOT NULL DEFAULT 20 CHECK (daily_goal BETWEEN 1 AND 500),
  notify            jsonb NOT NULL DEFAULT '{}'::jsonb
                    CHECK (jsonb_typeof(notify) = 'object'),
  active_profile_id uuid REFERENCES app.study_profile(id) ON DELETE SET NULL,
  updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER user_settings_touch BEFORE UPDATE ON app.user_settings
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

-- ============ hỗ trợ tra cứu & phản hồi chất lượng ============

-- Lịch sử tra cứu (UI hiện 50 từ gần nhất; job dọn định kỳ, không xoá lúc ghi).
CREATE TABLE app.search_history (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
  raw_query        text NOT NULL CHECK (btrim(raw_query) <> ''),
  normalized       text,
  language_id      smallint REFERENCES public.language(id),
  matched_sense_id bigint REFERENCES core.sense(id) ON DELETE SET NULL,
  result_count     integer CHECK (result_count >= 0),
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX search_history_recent ON app.search_history (user_id, created_at DESC);

-- Nút "báo lỗi nghĩa" là kênh kiểm duyệt duy nhất khi chưa có người duyệt.
-- target_id là chuỗi vì gloss có thể bị thay/xoá khi re-import (không FK cứng).
CREATE TABLE app.gloss_report (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     bigint REFERENCES app.users(id) ON DELETE SET NULL,
  target_kind text NOT NULL
              CHECK (target_kind IN ('sense_gloss', 'concept_gloss', 'example', 'translation')),
  target_id   text NOT NULL CHECK (btrim(target_id) <> ''),
  language_id smallint REFERENCES public.language(id),
  issue       text NOT NULL CHECK (issue IN ('wrong', 'missing', 'offensive', 'other')),
  comment     text,
  status      text NOT NULL DEFAULT 'open'
              CHECK (status IN ('open', 'triaged', 'fixed', 'rejected')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  CONSTRAINT gloss_report_resolved_pair CHECK (
    (status IN ('fixed', 'rejected')) = (resolved_at IS NOT NULL)
  )
);
CREATE INDEX gloss_report_queue ON app.gloss_report (status, created_at);
CREATE INDEX gloss_report_gloss ON app.gloss_report (target_kind, target_id);
