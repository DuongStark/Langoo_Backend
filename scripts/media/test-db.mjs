import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const requireRuntime = createRequire('/tmp/langoo-m141-r2-probe/package.json');
const { PGlite } = requireRuntime('@electric-sql/pglite');

export async function setup(t) {
  const db = new PGlite();
  await db.waitReady;
  t.after(() => db.close());
  await db.exec(`CREATE SCHEMA core; CREATE SCHEMA serve;
    CREATE TABLE core.concept(id bigint PRIMARY KEY,status text NOT NULL);
    CREATE TABLE core.sense(id bigint PRIMARY KEY, definition text);
    CREATE TABLE core.sense_concept(sense_id bigint REFERENCES core.sense(id),concept_id bigint REFERENCES core.concept(id),relation text,confidence real,verified boolean,PRIMARY KEY(sense_id,concept_id));
    CREATE TABLE core.media_asset(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,kind text NOT NULL CONSTRAINT media_asset_kind_check CHECK(kind IN('stroke_svg','stroke_gif','audio_tts')),object_key text NOT NULL UNIQUE,mime text NOT NULL,bytes integer CHECK(bytes>0),sha256 text,provider text,source_id integer,created_at timestamptz NOT NULL DEFAULT now());
    INSERT INTO core.concept VALUES(1,'curated'),(2,'draft'); INSERT INTO core.sense VALUES(11),(12);
    INSERT INTO core.sense_concept VALUES(11,1,'exact',1,true),(12,2,'exact',1,true);
    INSERT INTO core.media_asset(kind,object_key,mime) VALUES('stroke_svg','old.svg','image/svg+xml');`);
  await db.exec(readFileSync('db/migrations/045_concept_images.sql', 'utf8'));
  await db.exec(
    "CREATE TABLE public.schema_migration(name text);INSERT INTO public.schema_migration VALUES('045_concept_images.sql');INSERT INTO core.sense VALUES(13),(14);",
  );
  await db.exec("UPDATE core.sense SET definition='source ' || id;");
  return db;
}
export async function asset(db, key = 'image.png') {
  return (
    await db.query(
      `INSERT INTO core.media_asset(kind,object_key,mime,bytes,sha256,provider,metadata)
    VALUES('concept_image',$1,'image/png',100,$2,'r2','{"width":512,"height":512}') RETURNING id`,
      [key, 'a'.repeat(64)],
    )
  ).rows[0].id;
}
